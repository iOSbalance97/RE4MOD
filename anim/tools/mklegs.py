import numpy as np, struct
import mkmot
from conv import convert
from leon import PAR, OFF
from mot import euler_zyx, parse, eval_chan
M='/home/claude/re4mod/anim/mixamo/'
LEG=[(0,'pos'),(17,'rot'),(18,'rot'),(19,'rot'),(20,'rot'),(21,'rot'),(22,'rot'),(23,'rot'),(24,'rot'),(25,'rot'),(20,'pos'),(24,'pos')]
def legs(path):
    fr=convert(path)          # in place, 30 fps, includes the closing frame
    out=[]
    for vals,R,P in fr:
        v={}
        for no,k in LEG:
            if k=='pos' and no==0: v[(no,k)]=[0.0,float(P[0][1]),0.0]   # height bob only, in place
            elif k=='pos': v[(no,k)]=[float(x) for x in OFF[no]]     # ankle back on the shin (the aim
                                                                       # motion leaves its IK target there)
            else: v[(no,k)]=euler_zyx(R[PAR[no]].T@R[no])
        out.append((v,None,None))
    return out
clips=[('fwd','Pistol_Walk.fbx',2250),('back','Pistol_Walk_Backward.fbx',1600),('left','pistol strafe.fbx',1343),('right','pistol strafe (2).fbx',1597)]
mkmot.JOINTS=LEG
c=''
info=[]
for name,f,dist in clips:
    fr=legs(M+f)
    b=mkmot.build(fr,rot_tol=0.004)
    mf,ch=parse(b)
    info.append((name,mf,dist))
    print(name,'frames',mf,'bytes',len(b),'mm/cycle',dist)
    c+='unsigned char leg_%s[%d] __attribute__((aligned(32))) = {\n'%(name,len(b))
    for i in range(0,len(b),16): c+='  '+','.join('0x%02x'%x for x in b[i:i+16])+',\n'
    c+='};\n'
c+='/* name, cycle frames, millimetres Leon covers per cycle */\n'
c+='const short leg_cycle[4][2] = {'+','.join('{%d,%d}'%(mf,d) for _,mf,d in info)+'};\n'
open('/home/claude/gecko/c/leg_data.c','w').write('/* generated by anim/mklegs.py: Mixamo pistol walk / back / strafe legs (pelvis + legs, FK, in place) */\n'+c)
