# C0-03: Ashley's scared clip for the chapter 0 intro (user's Mixamo 'Scared.fbx') -> mod/c/ch0_scared.h
# Same retarget as mkcrouch.py (Leon's skeleton; Ashley has the same parts 0-25), parts 1-25 only, 10 fps.
import numpy as np, math
from conv import convert
from leon import PAR
from mot import euler_zyx
import mkcrouch_min as M
F='/home/claude/re4mod/anim/mixamo/ashley/Scared.fbx'
FPS=10; T0=2.2; T1=7.0
fr=convert(F,fps=FPS,inplace=True,t0=T0,t1=T1)   # the standing part: up at 2 s, down again at 7.5 s
r=-M.facing(fr)
Rr=M.Ry(r); rows=[]; ys=[]
for vals,R,P in fr:
    e=[]
    for p in range(1,26):
        L=R[PAR[p]].T@R[p]
        if PAR[p]==0: L=Rr@R[p]
        e+=[int(round(max(-3.2767,min(3.2767,a))*10000)) for a in euler_zyx(L)]
    rows.append(e); ys.append(int(round(P[0][1])))
n=len(rows)
out='/* generated by anim/tools/mkscared.py: Mixamo Scared, parts 1-25, %d fps */\n#define SC_N %d\n#define SC_FPS %d\n'%(FPS,n,FPS)
out+='static const s16 sc_rot[SC_N][75] = {\n'+',\n'.join('{'+','.join(map(str,e))+'}' for e in rows)+'};\n'
out+='static const s16 sc_y[SC_N] = {%s};\n'%','.join(map(str,ys))
open('/home/claude/re4mod/mod/c/ch0_scared.h','w').write(out)
print(n,'frames turn %.0f'%r,'y',min(ys),max(ys), 'root xz drift', np.round(fr[-1][2][0]-fr[0][2][0]))
