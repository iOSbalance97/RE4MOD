# Aim-walk pose tables for legs.c: per frame of each cycle, the local Euler (ZYX) of the pelvis and the
# leg parts, the pelvis height over the aim motion's root, and the chest sway / bob (deltas around the
# cycle mean) that legs.c lays on the upper body.
import numpy as np
from conv import convert
from leon import PAR
from mot import euler_zyx, rotm
M='/home/claude/re4mod/anim/mixamo/'
PARTS=[17,18,19,20,21,22,23,24,25]
clips=[('fwd','Pistol_Walk.fbx',2250,1028),('back','Pistol_Walk_Backward.fbx',1600,1028),
       ('left','pistol strafe.fbx',1343,1028),('right','pistol strafe (2).fbx',1597,1028)]
def quat(R):
    w=np.sqrt(max(0,1+R[0,0]+R[1,1]+R[2,2]))/2
    x=(R[2,1]-R[1,2])/(4*w); y=(R[0,2]-R[2,0])/(4*w); z=(R[1,0]-R[0,1])/(4*w)
    return np.array([w,x,y,z])
def qmat(q):
    w,x,y,z=q/np.linalg.norm(q)
    return np.array([[1-2*(y*y+z*z),2*(x*y-z*w),2*(x*z+y*w)],[2*(x*y+z*w),1-2*(x*x+z*z),2*(y*z-x*w)],[2*(x*z-y*w),2*(y*z+x*w),1-2*(x*x+y*y)]])
out='/* generated by anim/mkwalk.py */\n'
names=[]
for name,f,dist,base in clips:
    fr=convert(M+f)[:-1]          # cycle without the closing frame
    n=len(fr)
    legs=[];py=[];sway=[];bob=[]
    chest=[fr[i][1][2] for i in range(n)]
    qs=np.array([quat(R) for R in chest]); 
    for i in range(1,n):
        if np.dot(qs[i],qs[0])<0: qs[i]=-qs[i]
    qm=qs.mean(0); Rm=qmat(qm)
    cy=np.array([fr[i][2][2][1] for i in range(n)]); cym=cy.mean()
    for i,(vals,R,P) in enumerate(fr):
        legs.append([euler_zyx(R[PAR[p]].T@R[p]) for p in PARTS])
        py.append(P[0][1]-base)
        d=chest[i]@Rm.T                # chest orientation around its mean (world)
        sway.append(euler_zyx(d))
        bob.append(cy[i]-cym)
    a=np.unwrap(np.array(legs),axis=0)
    out+='static const f32 walk_%s_legs[%d][9][3] = {\n'%(name,n)+',\n'.join('{'+','.join('{%.5ff,%.5ff,%.5ff}'%tuple(v) for v in fr_)+'}' for fr_ in a)+'};\n'
    out+='static const f32 walk_%s_py[%d] = {'%(name,n)+','.join('%.2ff'%v for v in py)+'};\n'
    out+='static const f32 walk_%s_sway[%d][3] = {'%(name,n)+','.join('{%.5ff,%.5ff,%.5ff}'%tuple(v) for v in sway)+'};\n'
    out+='static const f32 walk_%s_bob[%d] = {'%(name,n)+','.join('%.2ff'%v for v in bob)+'};\n'
    names.append((name,n,dist))
    print(name,n,'sway max deg',np.degrees(np.abs(np.array(sway)).max(0)).round(1),'bob',round(float(np.ptp(bob)),1))
out+='typedef struct { int n; f32 dist; const f32 (*legs)[9][3]; const f32* py; const f32 (*sway)[3]; const f32* bob; } WalkClip;\n'
out+='static const WalkClip walk_clips[%d] = {\n'%len(names)+',\n'.join('{%d,%d.0f,walk_%s_legs,walk_%s_py,walk_%s_sway,walk_%s_bob}'%(n,d,nm,nm,nm,nm) for nm,n,d in names)+'};\n'
open('/home/claude/gecko/c/walk_data.h','w').write(out)
