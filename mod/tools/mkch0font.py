# C0-02: a small glyph atlas (GX I4) for the chapter 0 texts -> c/ch0_font.c
# Only the characters the texts use. Code 1 = the Cross button.
import numpy as np
from PIL import Image, ImageDraw, ImageFont
F = '/usr/share/fonts/truetype/crosextra/Caladea-Regular.ttf'
CARD = ['Cap\u00edtulo 0 \u2014 Hace 11 horas',
        'Ashley tiene que escapar del pueblo sin que la atrapen.',
        'Los ganados vigilan. La marca sobre su cabeza avisa:',
        'blanca, te intuye \u00b7 amarilla, sospecha \u00b7 roja, te ha visto.',
        '\x02  Agacharse: m\u00e1s lenta, pero tardan m\u00e1s en verte.',
        'L3  Correr: haces ruido.',
        '\x01  Esconderse donde se pueda.',
        'Si te atrapan, vuelves al \u00faltimo punto.',
        '\x01 Continuar']
TEXTS = CARD + ['Hace 11 horas', '“Tengo que salir de aquí.”', 'Está cerrada.',
         'Tiene que haber una llave en algún sitio.', '\x01 Coger la llave', 'Has cogido la llave.',
         'Ashley ha sido capturada', 'Fin de la Parte 1 (prueba)', 'La puerta se abre.', '\x01 Esconderse', '\x01 Salir', '!']
CH = sorted(set(''.join(TEXTS)) - {' '})
S = 3; SIZE = 18; GH = 24; W = 512   # C0-04: smaller cells (the dol is nearly full); hud.c scales by 4/3
f = ImageFont.truetype(F, SIZE * S)
asc, desc = f.getmetrics()
glyphs = []
for c in CH:
    if c == '\x02':                       # the Circle button
        w = 20
        im = Image.new('L', (w * S, GH * S), 0); dr = ImageDraw.Draw(im)
        r = 8 * S; x0 = 2 * S; y0 = (GH * S - 2 * r) // 2
        dr.ellipse((x0, y0, x0 + 2 * r, y0 + 2 * r), outline=255, width=2 * S)
        r2 = 4 * S; cx = x0 + r; cy = y0 + r
        dr.ellipse((cx - r2, cy - r2, cx + r2, cy + r2), outline=255, width=2 * S)
        adv = w
    elif c == '\x01':
        w = 20
        im = Image.new('L', (w * S, GH * S), 0); dr = ImageDraw.Draw(im)
        r = 8 * S; x0 = 2 * S; y0 = (GH * S - 2 * r) // 2
        dr.ellipse((x0, y0, x0 + 2 * r, y0 + 2 * r), outline=255, width=2 * S)
        m = 5 * S; dr.line((x0 + m, y0 + m, x0 + 2 * r - m, y0 + 2 * r - m), fill=255, width=3 * S)
        dr.line((x0 + 2 * r - m, y0 + m, x0 + m, y0 + 2 * r - m), fill=255, width=3 * S)
        adv = w
    else:
        adv = f.getlength(c) / S
        w = int(adv + 4)
        im = Image.new('L', (w * S, GH * S), 0); dr = ImageDraw.Draw(im)
        dr.text((2 * S, (GH * S - (asc + desc)) // 2), c, font=f, fill=255)
    glyphs.append((c, im.resize((w, GH), Image.LANCZOS), adv))
x = y = 0; tab = {}; rows = 1
atlas = np.zeros((GH * 4, W), np.float32)
for c, im, adv in glyphs:
    w = im.size[0]
    if x + w > W: x = 0; y += GH; rows += 1
    atlas[y:y + GH, x:x + w] = np.maximum(atlas[y:y + GH, x:x + w], np.array(im, np.float32))
    tab[c] = (x, y, w, adv); x += w
H = rows * GH
q = np.clip(np.round(atlas[:H] / 17.0), 0, 15).astype(np.uint8)
out = bytearray()
for ty in range(0, H, 8):
    for tx in range(0, W, 8):
        for r in q[ty:ty + 8, tx:tx + 8]: out += bytes((r[i] << 4) | r[i + 1] for i in range(0, 8, 2))
Image.fromarray((q * 17).astype(np.uint8)).save('/tmp/ch0_font.png')
src = ['/* generated by tools/mkch0font.py: chapter 0 glyph atlas (GX I4 %dx%d) */' % (W, H), '#include "game.h"',
       'const int ch0_font_w = %d, ch0_font_h = %d, ch0_font_gh = %d, ch0_font_space = %d;' % (W, H, GH, round(f.getlength(' ') / S)),
       'const u8 ch0_font[] __attribute__((aligned(32))) = {']
for i in range(0, len(out), 32): src.append(' ' + ','.join(str(v) for v in out[i:i + 32]) + ',')
src.append('};')
CP = {'\u201c': 0x93, '\u201d': 0x94, '\u2014': 0x97, '\u00b7': 0xB7}
idx = [0] * 256; gl = []
for c, (gx, gy, gw, adv) in tab.items():
    code = CP.get(c, ord(c)); assert code < 256, c
    gl.append((gx, gy, gw, round(adv * 4))); idx[code] = len(gl)
src.append('const u8 ch0_gidx[256] = {' + ','.join(map(str, idx)) + '};   /* Latin-1 code -> glyph + 1 */')
src.append('const u16 ch0_glyph[][4] = {   /* x, y, w, advance (x4) */')
src += ['    { %d, %d, %d, %d },' % g for g in gl]
src.append('};')
open('c/ch0_font.c', 'w').write('\n'.join(src) + '\n')
print('atlas', W, H, len(out), 'bytes,', len(tab), 'glyphs')
