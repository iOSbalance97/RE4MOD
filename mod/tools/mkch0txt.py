# C0-01: Chapter 0 texts (Spanish) drawn to GX I4 textures -> c/ch0_text.c
import numpy as np
from PIL import Image, ImageDraw, ImageFont
F = '/usr/share/fonts/truetype/crosextra/Caladea-%s.ttf'
def tex(text, W, H, size, style='Regular', track=0):
    S = 3
    im = Image.new('L', (W * S, H * S), 0); dr = ImageDraw.Draw(im)
    f = ImageFont.truetype(F % style, size * S)
    tw = sum(dr.textlength(c, font=f) for c in text) + track * S * (len(text) - 1)
    x = (W * S - tw) / 2; asc, desc = f.getmetrics(); y = (H * S - (asc + desc)) / 2
    for c in text:
        dr.text((x, y), c, font=f, fill=255); x += dr.textlength(c, font=f) + track * S
    img = np.array(im.resize((W, H), Image.LANCZOS)).astype(np.float32)
    q = np.clip(np.round(img / 17.0), 0, 15).astype(np.uint8)
    out = bytearray()
    for ty in range(0, H, 8):
        for tx in range(0, W, 8):
            for r in q[ty:ty + 8, tx:tx + 8]: out += bytes((r[i] << 4) | r[i + 1] for i in range(0, 8, 2))
    Image.fromarray((q * 17).astype(np.uint8)).save('/tmp/ch0_%d.png' % len(out))
    return out
T = [('ch0_t_hace', 'Hace 11 horas', 384, 64, 44, 'Regular', 3),
     ('ch0_t_salir', '“Tengo que salir de aquí.”', 512, 40, 26, 'Italic', 0),
     ('ch0_t_fin', 'Fin del Capítulo 0 (prueba)', 512, 40, 26, 'Regular', 1)]
src = ['/* generated by tools/mkch0txt.py: chapter 0 texts, GX I4 */', '#include "game.h"']
for name, text, W, H, size, st, tr in T:
    b = tex(text, W, H, size, st, tr)
    src.append('const u8 %s[] __attribute__((aligned(32))) = {' % name)
    for i in range(0, len(b), 32): src.append(' ' + ','.join(str(v) for v in b[i:i + 32]) + ',')
    src.append('};')
open('c/ch0_text.c', 'w').write('\n'.join(src) + '\n')
print('ok')
