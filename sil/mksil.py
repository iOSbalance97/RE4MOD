FLIP_H={0x03,0x21}
def i4(img):
    W,H=img.size; px=img.load(); out=bytearray()
    for ty in range(0,H,8):
        for tx in range(0,W,8):
            for y in range(8):
                for x in range(0,8,2):
                    a=px[tx+x,ty+y]>>4; b=px[tx+x+1,ty+y]>>4
                    out.append((a<<4)|b)
    return bytes(out)
def gen_c(path):
    ents=[];blob=b''
    for i in IDS:
        im=sil(i)
        if not im: continue
        if i in FLIP_H: im=im.transpose(Image.FLIP_LEFT_RIGHT)
        im=im.resize((64,32),Image.LANCZOS)
        ents.append((i,len(blob))); blob+=i4(im)
    with open(path,'w') as f:
        f.write('/* generated by sil/mksil.py: weapon silhouettes, 64x32 GX I4, one per item id */\n')
        f.write('#include "game.h"\nconst u8 sil_tex[] __attribute__((aligned(32))) = {\n')
        for k in range(0,len(blob),16): f.write(' '+','.join(str(b) for b in blob[k:k+16])+',\n')
        f.write('};\nconst u16 sil_ids[] = {'+','.join(hex(i) for i,_ in ents)+'};\n')
        f.write(f'const int sil_count = {len(ents)};\n')
    print(len(ents),'silhouettes',len(blob),'bytes')
