def sil(id_, size=(256,128)):
    p=f'/home/claude/disc/ext1/files/ss/Item/idm{id_:03d}.bin'
    if not os.path.exists(p): return None
    d=open(p,'rb').read()
    m=meshbin.parse(d)
    pts=[m.position(i) for i in range(len(m.vtx))]
    xs=[p[0] for p in pts]; ys=[p[1] for p in pts]; zs=[p[2] for p in pts]
    ext=[max(a)-min(a) for a in (xs,ys,zs)]
    ax=sorted(range(3),key=lambda k:-ext[k])[:2]   # two largest axes: horizontal, vertical
    u,v=ax
    if ext[u]<ext[v]: u,v=v,u
    W,H=size; pad=6
    sc=min((W-2*pad)/ext[u],(H-2*pad)/ext[v])
    mn=[min(xs),min(ys),min(zs)]
    cx=(W-ext[u]*sc)/2; cy=(H-ext[v]*sc)/2
    img=Image.new('L',(W,H),0); dr=ImageDraw.Draw(img)
    for part in m.parts:
        for t in part.triangles():
            poly=[(cx+(pts[vi[0]][u]-mn[u])*sc, H-(cy+(pts[vi[0]][v]-mn[v])*sc)) for vi in t]
            dr.polygon(poly,fill=255)
    return img
