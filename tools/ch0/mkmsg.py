# C0-10: the chapter's texts in the game's own message codes -> mod/c/ch0_msg.h
# Original lines are copied from the rooms' Spanish MDT (r101); the page breaks (08 04) become line breaks (03)
# and the final wait (08) goes, so they show without stopping the game.
import mdt
def orig(path,no):
    s=mdt.msgs(path,5)[no]; out=[]; i=0
    while i<len(s):
        if s[i]==8 and i+1<len(s) and s[i+1]==4: out.append(3); i+=2; continue
        if s[i]==8: i+=1; continue
        out.append(s[i]); i+=1
    while len(out)>1 and out[-2]==0x80: del out[-2]          # trailing space
    return out
CH={' ':0x80,'.':0x95,',':0x94,'!':0x9a,'¡':0x121,'á':0xef,'é':0xf0,'í':0xf1,'ó':0xf2,'ú':0xf3,'ñ':0x10b}
def enc(t):
    o=[0]
    for c in t:
        if c in CH: o.append(CH[c])
        elif 'a'<=c<='z': o.append(0xC1+ord(c)-97)
        elif 'A'<=c<='Z': o.append(0xA7+ord(c)-65)
        else: raise ValueError(c)
    return o+[1]
M=[('MSG_LOCKED',orig('/tmp/r101.bin',1),'r101 #1: Esta cerrada y no se abre. / Hay una especie de simbolo en la puerta.'),
   ('MSG_USED',orig('/tmp/r101.bin',20),'r101 #20: Has usado la <Llave de la insignia>.'),
   ('MSG_ASHLEY',enc('Tengo que salir de aquí.'),'Ashley, intro'),
   ('MSG_HURRY',enc('Ya vienen. Debo darme prisa.'),'Ashley, out of the house (C0-14)')]
with open('/home/claude/re4mod/mod/c/ch0_msg.h','w') as f:
    f.write('/* generated by tools/ch0/mkmsg.py: game message codes */\n')
    for n,c,cm in M:
        f.write('/* %s */\nstatic const u16 %s[] = { %s };\n'%(cm,n,', '.join('0x%X'%v for v in c)))
for n,c,cm in M: print(n,mdt.text(c))
